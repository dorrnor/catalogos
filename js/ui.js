// Botón "atrás" del celular: cierra primero lo que esté abierto (ventanas, modo elegir)
// y después vuelve a la pantalla anterior.

const layers = [];
let pendingPops = 0;
let router = () => {};

export function setRouter(fn) {
  router = fn;
}

export function pushLayer(close) {
  layers.push(close);
  history.pushState({ layer: layers.length }, '');
}

export function popLayers(n = 1) {
  n = Math.min(n, layers.length);
  if (!n) return;
  pendingPops += n;
  history.go(-n);
}

window.addEventListener('popstate', () => {
  if (layers.length) {
    let n = Math.max(1, pendingPops);
    pendingPops = 0;
    while (n-- > 0 && layers.length) layers.pop()();
    return;
  }
  pendingPops = 0;
  router();
});

